// 1. declare an int, a double, and a bool, assign them values and print all three on one line

#include <iostream>

int main() {
	
	int ex_integer{67};
	double ex_double{3.14};
	bool ex_boolean{1};

	std::cout << "Integer value: " << ex_integer << " ";
	std::cout << "Double value: " << ex_double << " ";
	std::cout << "Boolean value: " << ex_boolean << "\n";

	return 0;
}
